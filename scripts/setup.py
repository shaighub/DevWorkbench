#!/usr/bin/env python3
"""Publish DevWorkbench agents to the local coding tool.

The skill directories under agents/<agent>/skills/ stay the source of truth.
This script discovers those agents and installs the files each tool reads.

Usage:
    setup.cmd <claude|cursor|opencode|all> [--copy|--link] [--clean] [--sync]
    ./setup.sh <claude|cursor|opencode|all> [--copy|--link] [--clean] [--sync]
    python3 scripts/setup.py <claude|cursor|opencode|all> [--copy|--link]

Windows copies on the first run. Other platforms symlink each skill file
from a real directory named with the skill id. Re-running keeps that mode.
``--sync`` with no target refreshes whatever this checkout last installed.
``--clean`` removes the files this script generated.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path

MARKER = "Generated by scripts/setup.py"
MANIFEST_REL = ".devworkbench/setup-manifest.json"
ADAPTERS_REL = "shared/tool-adapters/adapters.json"
KEBAB = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
MAX_NAME = 64


@dataclass
class Skill:
    agent_id: str
    directory_name: str
    source: Path
    name: str
    description: str
    relative_source: str
    config_name: str | None = None


@dataclass
class Agent:
    id: str
    display_name: str
    orchestrator: str
    config: str | None
    gates: str | None
    handoff: str | None
    output_root: str | None
    validation_cycles: int | None
    skills: list[Skill] = field(default_factory=list)


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def valid_kebab(name: str) -> bool:
    return bool(KEBAB.fullmatch(name)) and len(name) <= MAX_NAME


def one_line(text: str) -> str:
    return " ".join(text.split())


def yaml_double(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def configure_stdio() -> None:
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        try:
            reconfigure(encoding="utf-8")
        except (OSError, ValueError):
            pass


def fail(message: str) -> None:
    raise SystemExit(message)


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        fail(f"Cannot read {path}: {exc}")
    return ""


def parse_frontmatter(text: str) -> dict[str, str]:
    if text.startswith("\ufeff"):
        text = text.lstrip("\ufeff")
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    end = None
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            end = index
            break
    if end is None:
        return {}
    data: dict[str, str] = {}
    index = 1
    while index < end:
        line = lines[index]
        if not line.strip() or line.lstrip().startswith("#") or line[:1] in (" ", "\t"):
            index += 1
            continue
        if ":" not in line:
            index += 1
            continue
        key, _, raw = line.partition(":")
        key = key.strip()
        raw = raw.strip()
        if raw in {">", ">-", ">+", "|", "|-", "|+"}:
            block: list[str] = []
            index += 1
            while index < end and (
                lines[index].startswith((" ", "\t")) or lines[index].strip() == ""
            ):
                block.append(lines[index].strip())
                index += 1
            if raw.startswith(">"):
                data[key] = " ".join(part for part in block if part).strip()
            else:
                data[key] = "\n".join(block).strip()
            continue
        if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in {'"', "'"}:
            quote = raw[0]
            raw = raw[1:-1]
            if quote == '"':
                raw = raw.replace('\\"', '"').replace("\\\\", "\\")
        data[key] = raw
        index += 1
    return data


def parse_config(text: str) -> dict[str, object]:
    agent_id = None
    agent_name = None
    paths: dict[str, str] = {}
    skills: list[dict[str, str]] = []
    cycles = None
    section = None
    current: dict[str, str] | None = None
    for line in text.splitlines():
        if line.startswith("agent:"):
            section = "agent"
            current = None
            continue
        if line.startswith("paths:"):
            section = "paths"
            current = None
            continue
        if line.startswith("skills:"):
            section = "skills"
            current = None
            continue
        if line.startswith("limits:"):
            section = "limits"
            current = None
            continue
        if line and not line.startswith(" "):
            section = None
            current = None
            continue
        if section == "agent" and line.startswith("  ") and not line.startswith("   "):
            key, _, value = line.strip().partition(":")
            value = value.strip()
            if key == "id":
                agent_id = value
            elif key == "name":
                agent_name = value
        elif section == "paths" and line.startswith("  ") and not line.startswith("   "):
            key, _, value = line.strip().partition(":")
            value = value.strip()
            if value:
                paths[key] = value
        elif section == "limits" and line.startswith("  maxValidationCycles:"):
            raw = line.split(":", 1)[1].strip()
            if raw.isdigit():
                cycles = int(raw)
        elif section == "skills" and line.startswith("  - id:"):
            current = {"id": line.split(":", 1)[1].strip().strip("\"'")}
            skills.append(current)
        elif section == "skills" and current is not None and line.startswith("    "):
            key, _, value = line.strip().partition(":")
            value = value.strip().strip("\"'")
            if key in {"directory", "name"} and value:
                current[key] = value
    return {
        "id": agent_id,
        "name": agent_name,
        "paths": paths,
        "skills": skills,
        "validation_cycles": cycles,
    }


def discover(root: Path) -> list[Agent]:
    agents_dir = root / "agents"
    if not agents_dir.is_dir():
        fail(f"No agents directory at {agents_dir}")
    found: list[Agent] = []
    names: dict[str, str] = {}
    for agent_dir in sorted(path for path in agents_dir.iterdir() if path.is_dir()):
        if agent_dir.name.startswith((".", "_")):
            continue
        orchestrator = agent_dir / "agent" / "orchestrator.md"
        skills_root = agent_dir / "skills"
        skill_dirs = []
        if skills_root.is_dir():
            skill_dirs = sorted(
                path
                for path in skills_root.iterdir()
                if path.is_dir() and (path / "SKILL.md").is_file()
            )
        if not orchestrator.is_file():
            if skill_dirs:
                fail(
                    f"{agent_dir.name} has skills and no "
                    f"{orchestrator.relative_to(root).as_posix()}"
                )
            continue
        if not valid_kebab(agent_dir.name):
            fail(f"Agent directory {agent_dir.name} must be lowercase kebab-case.")
        if not skill_dirs:
            print(
                f"skip {agent_dir.name}: orchestrator present, no SKILL.md files",
                file=sys.stderr,
            )
            continue
        config_path = agent_dir / "agent" / "config.yaml"
        parsed: dict[str, object] = {
            "id": None,
            "name": None,
            "paths": {},
            "skills": [],
            "validation_cycles": None,
        }
        if config_path.is_file():
            parsed = parse_config(read_text(config_path))
            if parsed["id"] and parsed["id"] != agent_dir.name:
                fail(
                    f"{config_path.relative_to(root).as_posix()} id is "
                    f"{parsed['id']!r}; the agent directory is {agent_dir.name!r}."
                )
        config_skills = list(parsed["skills"])  # type: ignore[arg-type]
        by_dir = {entry.get("directory"): entry for entry in config_skills}
        disk = {f"skills/{path.name}": path for path in skill_dirs}
        if config_path.is_file() and set(by_dir) != set(disk):
            missing = sorted(set(by_dir) - set(disk))
            extra = sorted(set(disk) - set(by_dir))
            fail(
                f"{config_path.relative_to(root).as_posix()} does not match "
                f"the skill directories. Missing {missing or '[]'}, "
                f"extra {extra or '[]'}."
            )
        ordered_dirs = [disk[entry["directory"]] for entry in config_skills] if config_skills else skill_dirs
        paths = parsed["paths"]  # type: ignore[assignment]
        agent = Agent(
            id=agent_dir.name,
            display_name=str(parsed["name"] or agent_dir.name.replace("-", " ").title()),
            orchestrator=orchestrator.relative_to(root).as_posix(),
            config=config_path.relative_to(root).as_posix() if config_path.is_file() else None,
            gates=_existing(root, paths.get("gates")) or _existing(root, "docs/sdlc-gates.md"),
            handoff=_existing(root, paths.get("handoff")) or _existing(root, "docs/agent-handoff.md"),
            output_root=paths.get("outputRoot") or None,
            validation_cycles=parsed["validation_cycles"],  # type: ignore[arg-type]
        )
        for skill_dir in ordered_dirs:
            if not valid_kebab(skill_dir.name):
                fail(f"Skill directory {skill_dir.name} must be lowercase kebab-case.")
            expected = f"{agent.id}-{skill_dir.name}"
            skill_md = skill_dir / "SKILL.md"
            front = parse_frontmatter(read_text(skill_md))
            relative = skill_md.relative_to(root).as_posix()
            if "name" not in front:
                fail(
                    f"{relative} is missing YAML frontmatter name. "
                    f"Expected name: {expected}"
                )
            name = front["name"].strip()
            description = front.get("description", "").strip()
            if not description:
                fail(f"{relative} is missing a YAML frontmatter description.")
            if name != expected or not valid_kebab(name):
                fail(
                    f"{relative}: name is {name!r}, expected {expected!r}. "
                    "Use <agent-id>-<skill-directory>, lowercase kebab-case, "
                    f"at most {MAX_NAME} characters."
                )
            entry = by_dir.get(f"skills/{skill_dir.name}", {})
            config_name = entry.get("name")
            if config_name and config_name != name:
                fail(
                    f"{config_path.relative_to(root).as_posix()} lists "
                    f"{config_name!r} for skills/{skill_dir.name}, and "
                    f"{relative} is named {name!r}."
                )
            if name in names:
                fail(f"Duplicate skill name {name} ({names[name]} and {relative}).")
            names[name] = relative
            agent.skills.append(
                Skill(
                    agent_id=agent.id,
                    directory_name=skill_dir.name,
                    source=skill_dir,
                    name=name,
                    description=description,
                    relative_source=skill_dir.relative_to(root).as_posix(),
                    config_name=config_name,
                )
            )
        found.append(agent)
    if not found:
        fail("No agents with an orchestrator and skills were found under agents/.")
    return found


def _existing(root: Path, relative: object) -> str | None:
    if not isinstance(relative, str) or not relative:
        return None
    path = root / relative
    if path.is_file():
        return relative
    return None


def load_adapters(root: Path) -> dict[str, object]:
    path = root / ADAPTERS_REL
    if not path.is_file():
        fail(f"Missing {ADAPTERS_REL}")
    try:
        data = json.loads(read_text(path))
    except json.JSONDecodeError as exc:
        fail(f"{ADAPTERS_REL} is not valid JSON: {exc}")
    if not isinstance(data, dict) or not isinstance(data.get("targets"), dict):
        fail(f"{ADAPTERS_REL} needs a targets object.")
    for key in ("instructions", "command"):
        if not isinstance(data.get(key), str):
            fail(f"{ADAPTERS_REL} needs a {key} template name.")
        template_file(root, data[key])
    targets = data["targets"]
    if not targets:
        fail(f"{ADAPTERS_REL} has no targets.")
    if "all" in targets:
        fail("An adapter cannot be named 'all'.")
    for name, spec in targets.items():
        if not valid_kebab(str(name)):
            fail(f"Adapter name {name!r} must be lowercase kebab-case.")
        if not isinstance(spec, dict):
            fail(f"Adapter {name} must be an object.")
        for field_name in ("instruction", "skills", "commands"):
            if field_name not in spec:
                fail(f"Adapter {name} is missing {field_name} (use null if the tool has none).")
            check_rel(f"{name}.{field_name}", spec[field_name])
        if not any(spec.get(field_name) for field_name in ("instruction", "skills", "commands")):
            fail(f"Adapter {name} publishes nothing.")
        for field_name in ("instructions", "command"):
            if field_name in spec and spec[field_name] is not None:
                if not isinstance(spec[field_name], str):
                    fail(f"Adapter {name} {field_name} must be a template path or null.")
                template_file(root, spec[field_name])
    return data


def check_rel(label: str, value: object) -> None:
    if value is None:
        return
    if not isinstance(value, str) or not value or value.startswith(("/", "\\")):
        fail(f"{label} must be a relative path.")
    parts = Path(value).parts
    if any(part in {"..", ""} for part in parts):
        fail(f"{label} must stay inside the repository.")


def template_file(root: Path, relative: str) -> Path:
    check_rel(relative, relative)
    base = (root / "shared" / "tool-adapters").resolve()
    path = (base / relative).resolve()
    try:
        path.relative_to(base)
    except ValueError:
        fail(f"Template {relative} must stay in shared/tool-adapters/.")
    if not path.is_file():
        fail(f"Missing template shared/tool-adapters/{relative}")
    return path


def render(template: str, mapping: dict[str, str]) -> str:
    def replace(match: re.Match[str]) -> str:
        key = match.group(1)
        if key not in mapping:
            fail(f"Template token {match.group(0)} has no value.")
        return mapping[key]

    return re.sub(r"\{\{([A-Z0-9_]+)\}\}", replace, template)


def agents_block(agents: list[Agent]) -> str:
    blocks: list[str] = ["## Agents", ""]
    for agent in agents:
        blocks.append(f"### {agent.display_name} (`{agent.id}`)")
        blocks.append("")
        blocks.append(f"- Orchestrator: `{agent.orchestrator}`")
        if agent.config:
            blocks.append(f"- Config: `{agent.config}`")
        if agent.gates:
            blocks.append(f"- Gates: `{agent.gates}`")
        if agent.handoff:
            blocks.append(f"- Handoff: `{agent.handoff}`")
        if agent.output_root:
            blocks.append(f"- Output: `{agent.output_root}/<engagement-id>/`")
        if agent.validation_cycles is not None:
            blocks.append(f"- Validation cycle limit: {agent.validation_cycles}")
        blocks.append(f"- Command: `/{agent.id}`")
        blocks.append("")
        blocks.append("Skills, in order:")
        blocks.append("")
        for index, skill in enumerate(agent.skills, start=1):
            blocks.append(f"{index}. `{skill.name}` — {one_line(skill.description)}")
            blocks.append(f"   Source: `{skill.relative_source}/`")
            blocks.append("")
        blocks.append("")
    return "\n".join(blocks).rstrip() + "\n"


def skill_list(agent: Agent) -> str:
    lines: list[str] = []
    for index, skill in enumerate(agent.skills, start=1):
        lines.append(f"{index}. `{skill.name}` — {one_line(skill.description)}")
        lines.append(f"   Source: `{skill.relative_source}/`")
        lines.append("")
    return "\n".join(lines).rstrip()


def output_hint(agent: Agent) -> str:
    if agent.output_root:
        return (
            f"Write the engagement under `{agent.output_root}/<engagement-id>/`. "
            "Preserve the source unchanged in `source/`."
        )
    return "Preserve the source unchanged, and write the package where the orchestrator says to write it."


def command_body(root: Path, adapters: dict[str, object], spec: dict[str, object], agent: Agent) -> str:
    template_name = spec.get("command") or adapters["command"]
    template = read_text(template_file(root, str(template_name)))
    description = (
        f"Run the {agent.display_name} (/{agent.id}) on a high-level need "
        "and stop at a proposed package."
    )
    config_line = f"`{agent.config}`" if agent.config else "the agent config, if a config.yaml is present,"
    gates = f"`{agent.gates}`" if agent.gates else "the gate document named by the orchestrator"
    handoff = f"`{agent.handoff}`" if agent.handoff else "the handoff document named by the orchestrator"
    text = render(
        template,
        {
            "DESCRIPTION": yaml_double(description),
            "DISPLAY_NAME": agent.display_name,
            "AGENT_ID": agent.id,
            "ORCHESTRATOR": agent.orchestrator,
            "CONFIG": config_line,
            "GATES": gates,
            "HANDOFF": handoff,
            "OUTPUT_HINT": output_hint(agent),
            "SKILL_LIST": skill_list(agent),
        },
    )
    if not text.endswith("\n"):
        text += "\n"
    return text


def instructions_body(root: Path, adapters: dict[str, object], spec: dict[str, object], agents: list[Agent]) -> str:
    template_name = spec.get("instructions") or adapters["instructions"]
    template = read_text(template_file(root, str(template_name)))
    text = render(template, {"AGENTS_BLOCK": agents_block(agents).rstrip()})
    if not text.endswith("\n"):
        text += "\n"
    if MARKER not in text:
        fail(f"Instruction template {template_name} is missing the generator marker.")
    return text


def rooted(root: Path, relative: str) -> Path:
    check_rel(relative, relative)
    return root.joinpath(*Path(relative).parts)


def remove_path(path: Path) -> None:
    """Remove a file, directory, or symlink without following a directory link."""
    if path.is_symlink():
        path.unlink()
        return
    if path.is_dir():
        shutil.rmtree(path)
        return
    if path.exists():
        path.unlink()


def prune_empty(path: Path, root: Path) -> None:
    current = path if path.exists() else path.parent
    while current != root and current.exists():
        if current.is_symlink() or not current.is_dir():
            return
        if any(current.iterdir()):
            return
        current.rmdir()
        current = current.parent


def iter_source_files(src: Path) -> list[Path]:
    files: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(src):
        current = Path(dirpath)
        dirnames[:] = sorted(
            name
            for name in dirnames
            if not name.startswith(".") and name != "__pycache__" and not (current / name).is_symlink()
        )
        for name in sorted(filenames):
            if name.startswith(".") or name == "__pycache__":
                continue
            files.append(current / name)
    return files


def place_file(src: Path, dest: Path, mode: str) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    # A symlink check has to win: rmtree on a directory link would delete the source.
    if dest.is_symlink() or dest.is_file():
        dest.unlink()
    elif dest.is_dir():
        shutil.rmtree(dest)
    if mode == "link":
        dest.symlink_to(os.path.relpath(src, dest.parent))
        return
    shutil.copy2(src, dest)


def unlink_directory_symlinks(dest: Path) -> None:
    """Unlink directory symlinks under dest. Do not follow them."""
    if not dest.exists() or dest.is_symlink() or not dest.is_dir():
        return
    found: list[Path] = []
    stack = [dest]
    while stack:
        current = stack.pop()
        try:
            children = list(current.iterdir())
        except OSError:
            continue
        for child in children:
            if not child.is_symlink():
                if child.is_dir():
                    stack.append(child)
                continue
            # File links are skill files. Directory links and broken links are not.
            try:
                is_file = child.is_file()
            except OSError:
                is_file = False
            if not is_file:
                found.append(child)
    for path in sorted(found, key=lambda item: len(item.parts), reverse=True):
        if path.is_symlink():
            path.unlink()


def sync_tree(src: Path, dest: Path, mode: str) -> None:
    if dest.is_symlink() or dest.is_file():
        dest.unlink()
    dest.mkdir(parents=True, exist_ok=True)
    unlink_directory_symlinks(dest)
    expected: set[str] = set()
    for src_file in iter_source_files(src):
        relative = src_file.relative_to(src).as_posix()
        expected.add(relative)
        place_file(src_file, dest / relative, mode)
    for dirpath, dirnames, filenames in os.walk(dest, topdown=False, followlinks=False):
        current = Path(dirpath)
        for name in filenames:
            path = current / name
            relative = path.relative_to(dest).as_posix()
            if relative not in expected and (path.is_symlink() or path.exists()):
                path.unlink()
        if current != dest and current.exists() and not current.is_symlink() and not any(current.iterdir()):
            current.rmdir()


def can_symlink(root: Path) -> bool:
    probe = root / ".devworkbench" / "symlink-probe"
    probe.mkdir(parents=True, exist_ok=True)
    target = probe / "target.txt"
    link = probe / "link.txt"
    ok = False
    try:
        target.write_text("ok", encoding="utf-8", newline="\n")
        if link.is_symlink() or link.exists():
            link.unlink()
        link.symlink_to("target.txt")
        ok = link.read_text(encoding="utf-8") == "ok"
    except OSError:
        ok = False
    finally:
        if link.is_symlink() or link.exists():
            link.unlink()
        if target.exists():
            target.unlink()
        if probe.is_dir() and not probe.is_symlink():
            probe.rmdir()
    return ok


def same_file(dest: Path, src: Path) -> bool:
    try:
        if not dest.exists() and not dest.is_symlink():
            return False
        if dest.is_symlink():
            return dest.resolve() == src.resolve()
        if dest.is_file():
            return dest.read_bytes() == src.read_bytes()
    except OSError:
        return False
    return False


def skill_dir_is_managed(dest: Path, src: Path) -> bool:
    if dest.is_symlink() or not dest.is_dir():
        return False
    src_files = {path.relative_to(src).as_posix(): path for path in iter_source_files(src)}
    if "SKILL.md" not in src_files:
        return False
    dest_files: list[str] = []
    for dirpath, dirnames, filenames in os.walk(dest, followlinks=False):
        current = Path(dirpath)
        kept: list[str] = []
        for name in dirnames:
            child = current / name
            if child.is_symlink():
                return False
            kept.append(name)
        dirnames[:] = kept
        dest_files.extend((current / name).relative_to(dest).as_posix() for name in filenames)
    if set(dest_files) != set(src_files):
        return False
    return all(same_file(dest / relative, src_file) for relative, src_file in src_files.items())


def gitignore_patterns(root: Path) -> list[str]:
    path = root / ".gitignore"
    if not path.is_file():
        return []
    patterns = []
    for line in read_text(path).splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or stripped.startswith("!"):
            continue
        patterns.append(stripped)
    return patterns


def gitignore_covers(relative: str, patterns: list[str]) -> bool:
    relative = relative.strip("/")
    for pattern in patterns:
        directory = pattern.endswith("/")
        body = pattern.strip().lstrip("/").rstrip("/")
        if not body or any(char in body for char in "*?["):
            continue
        if directory and (relative == body or relative.startswith(body + "/")):
            return True
        if not directory and relative == body:
            return True
    return False


def warn_if_unignored(root: Path, relative: str) -> None:
    if not gitignore_covers(relative, gitignore_patterns(root)):
        print(
            f"warning: {relative} is not covered by .gitignore; "
            "add an anchored rule before committing.",
            file=sys.stderr,
        )


def load_manifest(root: Path) -> dict[str, object]:
    path = rooted(root, MANIFEST_REL)
    if not path.is_file():
        return {"version": 1, "targets": {}}
    try:
        data = json.loads(read_text(path))
    except json.JSONDecodeError as exc:
        fail(f"{MANIFEST_REL} is not valid JSON ({exc}). Fix it or delete it and re-run.")
    if not isinstance(data, dict) or data.get("version") != 1 or not isinstance(data.get("targets"), dict):
        fail(f"{MANIFEST_REL} is not a version 1 setup manifest.")
    return data


def save_manifest(root: Path, manifest: dict[str, object]) -> None:
    path = rooted(root, MANIFEST_REL)
    if not manifest["targets"]:  # type: ignore[index]
        if path.exists() or path.is_symlink():
            remove_path(path)
        prune_empty(path.parent, root)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")


def write_generated(root: Path, relative: str, text: str) -> None:
    if MARKER not in text:
        fail(f"Refusing to write {relative} without the generator marker.")
    path = rooted(root, relative)
    if path.exists() and not path.is_symlink() and path.is_dir():
        fail(f"{relative} is a directory. Move it aside and re-run setup.")
    if path.is_file() and not path.is_symlink():
        current = read_text(path)
        if MARKER not in current:
            fail(
                f"{relative} already exists and was not generated by scripts/setup.py. "
                "Move it aside and re-run setup."
            )
    if path.is_symlink() or path.exists():
        path.unlink()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    warn_if_unignored(root, relative)


def mode_for(copy: bool, link: bool, recorded: str | None, platform: str) -> str:
    if copy and link:
        fail("Pass only one of --copy and --link.")
    if copy:
        return "copy"
    if link:
        return "link"
    if recorded in {"copy", "link"}:
        return recorded
    if platform == "win32":
        return "copy"
    return "link"


def owned_by_others(manifest: dict[str, object], target: str) -> set[str]:
    owned: set[str] = set()
    targets = manifest["targets"]  # type: ignore[index]
    for name, entry in targets.items():
        if name == target or not isinstance(entry, dict):
            continue
        owned.update(entry.get("paths", []))
    return owned


def publish_target(
    root: Path,
    adapters: dict[str, object],
    spec: dict[str, object],
    agents: list[Agent],
    mode: str,
) -> list[str]:
    paths: list[str] = []
    skills_dir = spec.get("skills")
    commands_dir = spec.get("commands")
    instruction = spec.get("instruction")
    # Write the instruction file first so a hand-written CLAUDE.md or AGENTS.md
    # stops the run before skill copies are published.
    if instruction:
        body = instructions_body(root, adapters, spec, agents)
        write_generated(root, str(instruction), body)
        paths.append(str(instruction))
    if commands_dir:
        for agent in agents:
            relative = f"{commands_dir}/{agent.id}.md"
            body = command_body(root, adapters, spec, agent)
            if MARKER not in body:
                fail("Command template is missing the generator marker.")
            write_generated(root, relative, body)
            paths.append(relative)
    if skills_dir:
        for agent in agents:
            for skill in agent.skills:
                relative = f"{skills_dir}/{skill.name}"
                sync_tree(skill.source, rooted(root, relative), mode)
                warn_if_unignored(root, relative)
                paths.append(relative)
    return sorted(set(paths))


def drop_stale(root: Path, old_paths: set[str], new_paths: set[str], still_owned: set[str]) -> None:
    for relative in sorted(old_paths - new_paths - still_owned):
        path = rooted(root, relative)
        remove_path(path)
        prune_empty(path.parent, root)


def apply_targets(
    root: Path,
    adapters: dict[str, object],
    names: list[str],
    copy: bool,
    link: bool,
    platform: str,
) -> None:
    agents = discover(root)
    manifest = load_manifest(root)
    modes = {
        name: mode_for(copy, link, _recorded(manifest, name), platform) for name in names
    }
    if "link" in modes.values() and not can_symlink(root):
        print(
            "Symlinks are unavailable (on Windows they need Developer Mode "
            "or an elevated prompt). Copying skill files instead. "
            "Re-run setup after editing a skill so the copies refresh.",
            file=sys.stderr,
        )
        modes = {name: "copy" for name in names}
    bodies: dict[str, str] = {}
    for name in names:
        spec = adapters["targets"][name]  # type: ignore[index]
        instruction = spec.get("instruction")
        if not instruction:
            continue
        body = instructions_body(root, adapters, spec, agents)
        previous = bodies.get(str(instruction))
        if previous is not None and previous != body:
            fail(f"{instruction} would be written twice with different text.")
        bodies[str(instruction)] = body
    used_copy = False
    for name in names:
        spec = adapters["targets"][name]  # type: ignore[index]
        mode = modes[name]
        old_paths = set(_paths(manifest, name))
        new_paths = publish_target(root, adapters, spec, agents, mode)
        manifest["targets"][name] = {"mode": mode, "paths": new_paths}  # type: ignore[index]
        drop_stale(root, old_paths, set(new_paths), owned_by_others(manifest, name))
        save_manifest(root, manifest)
        skill_count = sum(len(agent.skills) for agent in agents)
        print(f"{name}: installed {skill_count} skill(s) for {len(agents)} agent(s) ({mode})")
        if mode == "copy":
            used_copy = True
    if used_copy:
        print("Copies do not follow later edits. Re-run setup, or refresh with: setup.cmd --sync")
        print("On macOS or Linux the same refresh is: ./setup.sh --sync")
    else:
        print("Linked skill files follow source edits. Re-run setup after adding or renaming a file inside a skill.")


def _recorded(manifest: dict[str, object], target: str) -> str | None:
    entry = manifest["targets"].get(target)  # type: ignore[index]
    if isinstance(entry, dict) and entry.get("mode") in {"copy", "link"}:
        return str(entry["mode"])
    return None


def _paths(manifest: dict[str, object], target: str) -> list[str]:
    entry = manifest["targets"].get(target)  # type: ignore[index]
    if isinstance(entry, dict) and isinstance(entry.get("paths"), list):
        return [str(item) for item in entry["paths"]]
    return []


def marker_file(path: Path) -> bool:
    if not path.is_file() or path.is_symlink():
        return False
    try:
        return MARKER in path.read_text(encoding="utf-8")
    except OSError:
        return False


def recover_paths(root: Path, spec: dict[str, object], agents: list[Agent]) -> list[str]:
    found: list[str] = []
    skills_dir = spec.get("skills")
    commands_dir = spec.get("commands")
    instruction = spec.get("instruction")
    if skills_dir:
        for agent in agents:
            for skill in agent.skills:
                relative = f"{skills_dir}/{skill.name}"
                if skill_dir_is_managed(rooted(root, relative), skill.source):
                    found.append(relative)
    if commands_dir:
        for agent in agents:
            relative = f"{commands_dir}/{agent.id}.md"
            if marker_file(rooted(root, relative)):
                found.append(relative)
    # A shared instruction file is evidence for this target only when the
    # target still has its own skills or commands. Otherwise the file belongs
    # to whichever other target is still installed.
    if instruction and marker_file(rooted(root, str(instruction))):
        publishes_files = bool(skills_dir or commands_dir)
        if found or not publishes_files:
            found.append(str(instruction))
    return found


def clean_targets(root: Path, adapters: dict[str, object], names: list[str]) -> None:
    agents = discover(root)
    manifest = load_manifest(root)
    cleaning = set(names)
    keepers: set[str] = set()
    for other, spec in adapters["targets"].items():  # type: ignore[index]
        if other in cleaning or not isinstance(spec, dict):
            continue
        keepers.update(_paths(manifest, other))
        keepers.update(recover_paths(root, spec, agents))
    removed_any = False
    for name in names:
        spec = adapters["targets"][name]  # type: ignore[index]
        paths = set(recover_paths(root, spec, agents))
        if name in manifest["targets"]:  # type: ignore[operator]
            paths.update(_paths(manifest, name))
        manifest["targets"].pop(name, None)  # type: ignore[index]
        removed = 0
        for relative in sorted(paths):
            if relative in keepers:
                continue
            path = rooted(root, relative)
            if path.exists() or path.is_symlink():
                remove_path(path)
                prune_empty(path.parent, root)
                removed += 1
        save_manifest(root, manifest)
        if removed:
            removed_any = True
            print(f"{name}: removed generated files")
        else:
            print(f"{name}: nothing to remove")
    if not removed_any:
        print("Nothing to remove.")


def selected_targets(
    adapters: dict[str, object],
    target: str | None,
    manifest: dict[str, object],
    sync_only: bool,
) -> list[str]:
    known = list(adapters["targets"])  # type: ignore[arg-type]
    if target == "all":
        return known
    if target:
        return [target]
    if sync_only:
        recorded = [name for name in known if name in manifest["targets"]]  # type: ignore[operator]
        if not recorded:
            fail("Nothing to sync. Run setup.cmd all (or claude, cursor, opencode) first.")
        return recorded
    return known


def build_parser(adapters: dict[str, object]) -> argparse.ArgumentParser:
    names = list(adapters["targets"])  # type: ignore[arg-type]
    parser = argparse.ArgumentParser(
        prog="setup.py",
        description="Publish DevWorkbench skills to Claude Code, Cursor, and OpenCode.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "examples:\n"
            "  setup.cmd all\n"
            "  setup.cmd claude --copy\n"
            "  ./setup.sh cursor\n"
            "  python3 scripts/setup.py opencode --link\n"
            "  setup.cmd --sync\n"
            "  setup.cmd --clean\n"
        ),
    )
    parser.add_argument("target", nargs="?", choices=[*names, "all"])
    parser.add_argument("--copy", action="store_true", help="Copy skill files instead of symlinking them.")
    parser.add_argument("--link", action="store_true", help="Symlink each skill file. Falls back to copy.")
    parser.add_argument("--clean", action="store_true", help="Remove files generated for the target.")
    parser.add_argument(
        "--sync",
        action="store_true",
        help="Refresh the last install. With no target, every recorded target is refreshed.",
    )
    return parser


def main(argv: list[str] | None = None, platform: str | None = None) -> int:
    configure_stdio()
    root = repo_root()
    adapters = load_adapters(root)
    args = build_parser(adapters).parse_args(argv)
    if args.clean and (args.copy or args.link or args.sync):
        fail("--clean does not combine with --copy, --link, or --sync.")
    if args.target is None and not args.clean and not args.sync:
        fail("Name a target: claude, cursor, opencode, or all. Try setup.cmd all")
    manifest = load_manifest(root)
    names = selected_targets(adapters, args.target, manifest, sync_only=args.sync and args.target is None)
    if args.clean:
        clean_targets(root, adapters, names)
        return 0
    apply_targets(root, adapters, names, args.copy, args.link, platform or sys.platform)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SystemExit as exc:
        if isinstance(exc.code, str):
            print(exc.code, file=sys.stderr)
            sys.exit(1)
        raise
